-- 营养配方版本主表：同一 recipe_code 逐版递增；任一时间至多一个 PUBLISHED 版本；
-- status: DRAFT 草稿 / PENDING_APPROVAL 待处理（审批中）/ PUBLISHED 已发布 / ARCHIVED 已归档
CREATE TABLE IF NOT EXISTS t_pf_nutrient_recipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_code VARCHAR(40) NOT NULL,
    variety_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    target_ec DECIMAL(5,2) NOT NULL,
    nitrogen_ppm DECIMAL(8,2) NOT NULL,
    phosphorus_ppm DECIMAL(8,2) NOT NULL,
    potassium_ppm DECIMAL(8,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    remark VARCHAR(255),
    submitted_at TIMESTAMP,
    submitted_by BIGINT,
    published_at TIMESTAMP,
    published_by BIGINT,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_nutrient_recipe_ver UNIQUE (recipe_code, version_no)
);
CREATE INDEX IF NOT EXISTS idx_pf_nutrient_recipe_variety ON t_pf_nutrient_recipe (variety_id, status);

-- 微量元素明细（氮磷钾在主表，本表只放微量/中量元素，不允许重复 N/P/K）
CREATE TABLE IF NOT EXISTS t_pf_nutrient_recipe_element (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL,
    element_code VARCHAR(8) NOT NULL,
    concentration_ppm DECIMAL(8,3) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_nutrient_element UNIQUE (recipe_id, element_code)
);

-- 审批步骤留痕（只追加）：两级审批，集齐 2 级才发布；只有 1 级时配方停留 PENDING_APPROVAL
CREATE TABLE IF NOT EXISTS t_pf_nutrient_recipe_approval (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL,
    step_no INT NOT NULL,
    step_name VARCHAR(32) NOT NULL,
    approver_id BIGINT NOT NULL,
    approver_name VARCHAR(64) NOT NULL,
    comment VARCHAR(255),
    approved_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_nutrient_approval_step UNIQUE (recipe_id, step_no)
);

-- 元素兼容性规则：两元素共存浓度之和超过 max_sum_ppm 时禁止发布（如钙与磷酸盐共沉）
CREATE TABLE IF NOT EXISTS t_pf_nutrient_incompatibility (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    element_a VARCHAR(8) NOT NULL,
    element_b VARCHAR(8) NOT NULL,
    max_sum_ppm DECIMAL(10,2) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    create_by BIGINT,
