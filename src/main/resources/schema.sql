    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id BIGINT NOT NULL,
    greenhouse_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    recipe_id BIGINT,
    recipe_version INT,
    stage_code VARCHAR(32),
    override_id BIGINT,
    spectrum_red INT NOT NULL,
    spectrum_blue INT NOT NULL,
    spectrum_far_red INT NOT NULL,
    brightness_ppfd INT NOT NULL,
    light_on VARCHAR(5) NOT NULL,
    light_off VARCHAR(5) NOT NULL,
    effective_at TIMESTAMP NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_light_dispatch_hour UNIQUE (zone_id, effective_at)
);
CREATE INDEX IF NOT EXISTS idx_pf_light_dispatch_batch ON t_pf_light_dispatch (batch_id, stage_code);

-- 设备执行项（重试队列）：FAILED/RETRYING 且 next_retry_at 到点的记录由任务重发；
-- 超过最大重试次数置 DEAD，人工处理设备后可手动再触发
CREATE TABLE IF NOT EXISTS t_pf_light_dispatch_device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispatch_id BIGINT NOT NULL,
    device_id BIGINT NOT NULL,
    device_code VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    retry_count INT NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMP,
    last_error VARCHAR(255),
    sent_at TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_light_dispatch_device UNIQUE (dispatch_id, device_id)
);
CREATE INDEX IF NOT EXISTS idx_pf_light_dd_retry ON t_pf_light_dispatch_device (status, next_retry_at);

