    inbound_by BIGINT NOT NULL,
    inbound_name VARCHAR(64) NOT NULL,
    inbound_time TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_ns_lot UNIQUE (material_id, lot_no)
);
CREATE INDEX IF NOT EXISTS idx_pf_ns_material ON t_pf_nutrient_stock (material_id, status);
CREATE INDEX IF NOT EXISTS idx_pf_ns_expiry ON t_pf_nutrient_stock (expiry_date);

