-- 营养液原料目录：compat_group 用于母液罐兼容校验
--  CALCIUM 钙系（硝酸钙）/ PHOS_SULFUR 磷硫系（磷酸二氢钾、硫酸盐等）/ NEUTRAL 通用（硝酸盐、螯合微肥）
