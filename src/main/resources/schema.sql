-- 光配方版本主表：同一 recipe_code 逐版递增；任一时间至多一个 PUBLISHED 版本
CREATE TABLE IF NOT EXISTS t_pf_light_recipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_code VARCHAR(40) NOT NULL,
    variety_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    remark VARCHAR(255),
    published_at TIMESTAMP,
    published_by BIGINT,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_light_recipe_ver UNIQUE (recipe_code, version_no)
);
CREATE INDEX IF NOT EXISTS idx_pf_light_recipe_variety ON t_pf_light_recipe (variety_id, status);

-- 配方阶段明细：day_from <= 播种后天数 < day_to（day_to 空=开放段），光谱三项合计 100
CREATE TABLE IF NOT EXISTS t_pf_light_recipe_stage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL,
    stage_code VARCHAR(32) NOT NULL,
    stage_name VARCHAR(64) NOT NULL,
    day_from INT NOT NULL,
    day_to INT,
    spectrum_red INT NOT NULL,
    spectrum_blue INT NOT NULL,
    spectrum_far_red INT NOT NULL,
    brightness_ppfd INT NOT NULL,
    light_on VARCHAR(5) NOT NULL,
    light_off VARCHAR(5) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_light_stage_code UNIQUE (recipe_id, stage_code)
);

-- 灯控设备（隶属分区）；非 ACTIVE 设备下发失败，进入重试队列
CREATE TABLE IF NOT EXISTS t_pf_light_device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code VARCHAR(32) NOT NULL,
    zone_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
