CREATE TABLE IF NOT EXISTS t_pf_nutrient_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_code VARCHAR(32) NOT NULL,
    material_name VARCHAR(64) NOT NULL,
    nutrient_role VARCHAR(16) NOT NULL,
    compat_group VARCHAR(16) NOT NULL DEFAULT 'NEUTRAL',
    default_tank VARCHAR(8),
    unit VARCHAR(8) NOT NULL DEFAULT 'KG',
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_nm_code UNIQUE (material_code)
);

-- 原料批号库存：按批号入库，记录生产日期/有效期；过期批号任何补加都不允许使用
CREATE TABLE IF NOT EXISTS t_pf_nutrient_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL,
    lot_no VARCHAR(40) NOT NULL,
    inbound_qty_kg DECIMAL(12,3) NOT NULL,
